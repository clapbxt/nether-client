// Regenerates the name tables for every class_/field_/method_ (and legacy SRG func_/field_) name the overlay uses:
//  --official <tiny> <client.txt>   Fabric intermediary -> Mojang names (Forge/NeoForge, unobfuscated 26.x) into Names.java
//  --obf <mc> <tiny>                intermediary -> obfuscated name + descriptor for vanilla <mc>  -> res/names/<mc>.txt
//  --srg <mc> <srg>                 SRG (Forge deobfuscation_data, decompressed) -> notch name + descriptor -> res/names/<mc>.txt
// Every option may repeat. Names a version lacks are listed (the code must have a fallback for them).
//   node agent/tools/names.js --official int-1.21.11.tiny client-1.21.11.txt --obf 1.21.11 int-1.21.11.tiny --srg 1.12.2 srg-1.12.2.txt
const fs = require("fs"), path = require("path");
const src = path.join(__dirname, "..", "src", "dev", "nether", "ov"), res = path.join(__dirname, "..", "res", "names");
const lines = f => fs.readFileSync(f, "utf8").split("\n").map(l => l.replace("\r", ""));
const dot = s => s.split("/").join(".");
const used = new Set(["net.minecraft.class_1657", "method_7299", "net.minecraft.class_922", "method_4055", "net.minecraft.class_338", "net.minecraft.class_1297", "method_5872", "net.minecraft.class_4184", "method_19325"]), usedSrg = new Set(["net.minecraft.client.Minecraft"]); // + the game class (bind), the name, nametag-visibility and freelook hooks (Agent)
for (const f of fs.readdirSync(src)) {
  if (f === "Names.java") continue;
  const t = fs.readFileSync(path.join(src, f), "utf8");
  for (const m of t.matchAll(/net\.minecraft\.class_[0-9a-z_$]+|"(?:field|method|comp)_[0-9]+"/g)) used.add(m[0].split('"').join(""));
  for (const m of t.matchAll(/\bl\("[^"]*", "([^"]+)"\)/g)) usedSrg.add(m[1]);
}

function official(tinyFile, mojFile) {
  const mojToObf = {}, members = {}; // members[obfClass] = [{obf, name, params: [mojang types] | null}]
  let cur = null;
  for (const line of lines(mojFile)) {
    if (!line || line.startsWith("#")) continue;
    if (!line.startsWith(" ")) {
      const m = line.match(/^(\S+) -> (\S+):$/);
      cur = m[2]; mojToObf[m[1]] = cur; members[cur] = [];
    } else {
      const m = line.trim().match(/^(?:\d+:\d+:)?(\S+) (\S+?)(\((.*)\))? -> (\S+)$/);
      if (m) members[cur].push({ obf: m[5], name: m[2], params: m[3] ? (m[4] ? m[4].split(",") : []) : null });
    }
  }
  const obfToMoj = Object.fromEntries(Object.entries(mojToObf).map(([a, b]) => [b, a]));
  const prim = { int: "I", long: "J", boolean: "Z", byte: "B", char: "C", short: "S", float: "F", double: "D", void: "V" };
  const desc = t => { let a = ""; while (t.endsWith("[]")) { a += "["; t = t.slice(0, -2); } return a + (prim[t] || "L" + (mojToObf[t] || t).split(".").join("/") + ";"); };
  const out = {};
  for (const line of lines(tinyFile)) {
    const p = line.split("\t");
    if (p[0] === "CLASS") { const moj = obfToMoj[dot(p[1])]; if (used.has(dot(p[2])) && moj) out[dot(p[2])] = moj; }
    else if ((p[0] === "FIELD" || p[0] === "METHOD") && used.has(p[4])) {
      const ms = (members[dot(p[1])] || []).filter(m => m.obf === p[3] && (p[0] === "FIELD" ? m.params === null
        : m.params !== null && "(" + m.params.map(desc).join("") + ")" === p[2].slice(0, p[2].indexOf(")") + 1)));
      if (ms.length !== 1) { if (!out[p[4]]) console.error("ambiguous/missing", p[4], ms.length); continue; }
      out[p[4]] = ms[0].name;
    }
  }
  const missing = [...used].filter(u => !out[u]);
  if (missing.length) console.error("official: unmapped", missing.join(" "));
  const rows = Object.keys(out).sort().map(k => `        "${k}", "${out[k]}",`).join("\n");
  fs.writeFileSync(path.join(src, "Names.java"), `package dev.nether.ov;

import java.io.BufferedReader;
import java.io.ByteArrayInputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.Map;

/**
 * GENERATED by agent/tools/names.js. T: Fabric intermediary -> Mojang names of 1.21.11 (Forge, NeoForge, unobfuscated
 * 26.x). Obfuscated vanilla names come from res/names/<version>.txt (intermediary or SRG name, obfuscated name,
 * obfuscated descriptor), loaded only for the running version.
 */
final class Names {
    private Names() {}

    private static final String[] T = {
${rows}
    };
    private static final Map<String, String> M = new HashMap<>(), OB = new HashMap<>(), OD = new HashMap<>();

    static {
        for (int i = 0; i < T.length; i += 2) M.put(T[i], T[i + 1]);
    }

    /** Loads the obfuscated table of one version; false when the agent has none. */
    static boolean load(String version) {
        byte[] b = version == null ? null : dev.nether.agent.Hook.file.apply("names/" + version + ".txt");
        if (b == null) return false;
        try (BufferedReader r = new BufferedReader(new InputStreamReader(new ByteArrayInputStream(b), StandardCharsets.UTF_8))) {
            for (String l; (l = r.readLine()) != null; ) {
                String[] p = l.split("\\t", -1);
                if (p.length < 3) continue;
                OB.put(p[0], p[1]);
                OD.put(p[0], p[2]);
            }
            return true;
        } catch (Exception e) {
            return false;
        }
    }

    /** Mojang name for an intermediary one; unknown names pass through. */
    static String official(String n) { String o = M.get(n); return o == null ? n : o; }
    /** Obfuscated name for an intermediary/SRG one; unknown names pass through. */
    static String obf(String n) { String o = OB.get(n); return o == null ? n : o; }
    /** Obfuscated descriptor of a member (field type or method descriptor), null when unknown. */
    static String obfDesc(String n) { String d = OD.get(n); return d == null || d.isEmpty() ? null : d; }
}
`);
  console.log("official: " + Object.keys(out).length + " names");
}

function write(mc, obf, kind, want) {
  fs.mkdirSync(res, { recursive: true });
  const keys = Object.keys(obf).sort();
  fs.writeFileSync(path.join(res, mc + ".txt"), keys.map(k => k + "\t" + obf[k][0] + "\t" + obf[k][1]).join("\n") + "\n");
  const missing = [...want].filter(u => !obf[u]).sort();
  console.log(`${kind} ${mc}: ${keys.length} names` + (missing.length ? `, absent: ${missing.join(" ")}` : ""));
}

function obfTable(mc, tinyFile) { // tiny v1: CLASS obf inter | FIELD/METHOD owner desc obf inter
  const obf = {};
  for (const line of lines(tinyFile)) {
    const p = line.split("\t");
    if (p[0] === "CLASS" && used.has(dot(p[2]))) obf[dot(p[2])] = [dot(p[1]), ""];
    else if ((p[0] === "FIELD" || p[0] === "METHOD") && used.has(p[4])) {
      if (!obf[p[4]]) obf[p[4]] = [p[3], p[2]];
      else if (obf[p[4]][0] !== p[3] || obf[p[4]][1] !== p[2]) console.error(mc, "obf differs across owners", p[4]);
    }
  }
  write(mc, obf, "obf", used);
}

function srgTable(mc, srgFile) { // CL: notch mcp | FD: owner/notch mcp/owner/srg | MD: owner/notch desc mcp/owner/srg desc
  const obf = {};
  for (const line of lines(srgFile)) {
    const p = line.split(" ");
    if (p[0] === "CL:" && usedSrg.has(dot(p[2]))) obf[dot(p[2])] = [dot(p[1]), ""];
    else if (p[0] === "FD:" || p[0] === "MD:") {
      const s = p[p[0] === "FD:" ? 2 : 3], name = s.slice(s.lastIndexOf("/") + 1);
      if (!usedSrg.has(name) || obf[name]) continue;
      const o = p[1], d = p[0] === "MD:" ? p[2] : "";
      obf[name] = [o.slice(o.lastIndexOf("/") + 1), d];
    }
  }
  write(mc, obf, "srg", usedSrg);
}

const a = process.argv.slice(2);
for (let i = 0; i < a.length; i++) {
  if (a[i] === "--official") { official(a[i + 1], a[i + 2]); i += 2; }
  else if (a[i] === "--obf") { obfTable(a[i + 1], a[i + 2]); i += 2; }
  else if (a[i] === "--srg") { srgTable(a[i + 1], a[i + 2]); i += 2; }
}
