PX, UPM, CAP = 100, 800, 7
TOPS = {k: CAP for k in G}

def glyph(rows, bold):
    pen = TTGlyphPen(None)
    w = max(len(r) for r in rows)
    for ri, row in enumerate(rows):
        cells = [c == "#" for c in row.ljust(w, ".")]
        if bold:
            cells = [a or (i > 0 and cells[i-1]) for i, a in enumerate(cells + [False])]
        x = 0
        while x < len(cells):
            if cells[x]:
                s = x
                while x < len(cells) and cells[x]: x += 1
                y1 = (CAP - ri) * PX; y0 = y1 - PX
                # clockwise outer contour for TrueType
                pen.moveTo((s*PX, y0)); pen.lineTo((s*PX, y1)); pen.lineTo((x*PX, y1)); pen.lineTo((x*PX, y0)); pen.closePath()
            else:
                x += 1
    adv = (w + (1 if bold else 0) + 1) * PX
    return pen.glyph(), adv

def build(style):
    bold = style == "Bold"
    fb = FontBuilder(UPM, isTTF=True)
    names = [".notdef", "space"] + [f"u{ord(c):04X}" for c in G]
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap({32: "space", **{ord(c): f"u{ord(c):04X}" for c in G}})
    glyphs, metrics = {}, {}
    e = TTGlyphPen(None); glyphs[".notdef"] = e.glyph(); metrics[".notdef"] = (600, 0)
    e = TTGlyphPen(None); glyphs["space"] = e.glyph(); metrics["space"] = (400 if bold else 400, 0)
    for c, rows in G.items():
        gl, adv = glyph(rows, bold)
        n = f"u{ord(c):04X}"; glyphs[n] = gl; metrics[n] = (adv, 0)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({k: (v[0], glyphs[k].xMin if hasattr(glyphs[k], "xMin") and glyphs[k].numberOfContours else 0) for k, v in metrics.items()})
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable({"familyName": "Nether Pixel", "styleName": style,
                       "copyright": "Nether Client. SIL Open Font License 1.1"})
    fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, sTypoLineGap=0, usWinAscent=800, usWinDescent=200,
                sxHeight=500, sCapHeight=700, usWeightClass=700 if bold else 400, fsSelection=0x20 if bold else 0x40)
    fb.setupPost(); fb.setupHead(unitsPerEm=UPM, macStyle=1 if bold else 0)
    out = Path(__file__).with_name(f"NetherPixel-{style}.ttf")
    fb.save(str(out)); return out

for s in ("Regular", "Bold"):
    p = build(s); print(p, p.stat().st_size)
